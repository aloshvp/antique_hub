"""
PDF Generation Engine for Module 13 - Admin Dashboard Reports.
Built using ReportLab to generate publication-grade, styled PDF documents
with Antique Hub branding, metadata, summary statistics, and data tables.
"""

import io
from decimal import Decimal
from django.utils import timezone
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, KeepTogether
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.pdfgen import canvas


class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to dynamically compute and print 'Page X of Y' 
    and official running header/footer on all pages.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_decorations(self, page_count):
        self.saveState()
        width, height = self._pagesize

        # Running Top Accent Bar
        self.setFillColor(colors.HexColor("#2b1b17"))
        self.rect(0, height - 12, width, 12, fill=True, stroke=False)
        self.setFillColor(colors.HexColor("#d4af37"))
        self.rect(0, height - 14, width, 2, fill=True, stroke=False)

        # Running Footer
        self.setStrokeColor(colors.HexColor("#e0e0e0"))
        self.setLineWidth(0.75)
        self.line(36, 32, width - 36, 32)

        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#6c757d"))
        self.drawString(36, 20, "Antique Hub Management Console &bull; Confidential Administrative Audit Document")
        
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(width - 36, 20, page_str)
        self.restoreState()


def build_report_pdf(report_title, subtitle, metadata_dict, summary_kpis, headers, data_rows, col_widths=None):
    """
    Universal PDF report builder returning PDF binary bytes.
    
    Args:
        report_title: e.g. "SALES & REVENUE MASTER AUDIT REPORT"
        subtitle: Description or subtitle
        metadata_dict: Dict of key-value pairs (e.g. Generated By, Date Range, Filter Criteria)
        summary_kpis: List of tuples (Label, Value) for executive KPI summary cards
        headers: List of column header strings
        data_rows: List of lists containing cell values (strings/Paragraphs)
        col_widths: Optional list of explicit column widths in points
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=landscape(A4),
        leftMargin=36,
        rightMargin=36,
        topMargin=40,
        bottomMargin=45
    )

    styles = getSampleStyleSheet()

    # Custom typography styles
    title_style = ParagraphStyle(
        'RepTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=18,
        leading=22,
        textColor=colors.HexColor('#2b1b17')
    )

    brand_badge_style = ParagraphStyle(
        'RepBadge',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=9,
        leading=11,
        textColor=colors.HexColor('#d4af37')
    )

    subtitle_style = ParagraphStyle(
        'RepSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=13,
        textColor=colors.HexColor('#555555')
    )

    meta_key_style = ParagraphStyle(
        'RepMetaKey',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8,
        leading=11,
        textColor=colors.HexColor('#2b1b17')
    )

    meta_val_style = ParagraphStyle(
        'RepMetaVal',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8,
        leading=11,
        textColor=colors.HexColor('#333333')
    )

    table_header_style = ParagraphStyle(
        'RepTh',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8,
        leading=10,
        textColor=colors.HexColor('#ffffff'),
        alignment=1  # Centered
    )

    table_cell_style = ParagraphStyle(
        'RepTd',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=7.5,
        leading=10,
        textColor=colors.HexColor('#222222')
    )

    table_cell_center = ParagraphStyle(
        'RepTdCenter',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=7.5,
        leading=10,
        textColor=colors.HexColor('#222222'),
        alignment=1
    )

    table_cell_right = ParagraphStyle(
        'RepTdRight',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=7.5,
        leading=10,
        textColor=colors.HexColor('#1b5e20'),
        alignment=2
    )

    story = []

    # 1. Header Banner
    story.append(Paragraph("ANTIQUE HUB &bull; HERITAGE CURATIONS & COMMERCE PLATFORM", brand_badge_style))
    story.append(Spacer(1, 3))
    story.append(Paragraph(report_title.upper(), title_style))
    story.append(Spacer(1, 2))
    story.append(Paragraph(subtitle, subtitle_style))
    story.append(Spacer(1, 10))

    # 2. Metadata Grid Table
    meta_table_data = []
    meta_items = list(metadata_dict.items())
    for i in range(0, len(meta_items), 2):
        row = []
        k1, v1 = meta_items[i]
        row.append(Paragraph(f"{k1}:", meta_key_style))
        row.append(Paragraph(str(v1), meta_val_style))
        if i + 1 < len(meta_items):
            k2, v2 = meta_items[i + 1]
            row.append(Paragraph(f"{k2}:", meta_key_style))
            row.append(Paragraph(str(v2), meta_val_style))
        else:
            row.extend(["", ""])
        meta_table_data.append(row)

    if meta_table_data:
        meta_table = Table(
            meta_table_data,
            colWidths=[90, 290, 90, 290]
        )
        meta_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#fbf9f5')),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#e6dfd5')),
            ('INNERGRID', (0, 0), (-1, -1), 0.25, colors.HexColor('#f0ece4')),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ('LEFTPADDING', (0, 0), (-1, -1), 8),
            ('RIGHTPADDING', (0, 0), (-1, -1), 8),
        ]))
        story.append(meta_table)
        story.append(Spacer(1, 10))

    # 3. Summary KPI Box
    if summary_kpis:
        kpi_cells = []
        for label, val in summary_kpis:
            cell_p = Paragraph(
                f"<font size=7 color='#666666'><b>{label.upper()}</b></font><br/>"
                f"<font size=11 color='#2b1b17'><b>{val}</b></font>",
                table_cell_center
            )
            kpi_cells.append(cell_p)

        kpi_table = Table([kpi_cells], colWidths=[760 / len(summary_kpis)] * len(summary_kpis))
        kpi_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#f5eedc')),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor('#d4af37')),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#d4af37')),
            ('TOPPADDING', (0, 0), (-1, -1), 6),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ]))
        story.append(kpi_table)
        story.append(Spacer(1, 12))

    # 4. Main Data Table
    table_content = []
    # Header row
    th_row = [Paragraph(h, table_header_style) for h in headers]
    table_content.append(th_row)

    # Data rows
    for row in data_rows:
        formatted_row = []
        for i, val in enumerate(row):
            val_str = str(val if val is not None else "-")
            # Auto format currency or status
            if val_str.startswith("₹") or (val_str.replace('.', '', 1).isdigit() and i >= len(row) - 3):
                p = Paragraph(val_str, table_cell_right)
            elif val_str in ['Active', 'Paid', 'Delivered', 'Success', 'In Stock', 'Confirmed']:
                p = Paragraph(f"<font color='#2e7d32'><b>{val_str}</b></font>", table_cell_center)
            elif val_str in ['Pending', 'Unpaid', 'Shipped', 'Low Stock']:
                p = Paragraph(f"<font color='#e65100'><b>{val_str}</b></font>", table_cell_center)
            elif val_str in ['Inactive', 'Blocked', 'Cancelled', 'Failed', 'Out of Stock']:
                p = Paragraph(f"<font color='#c62828'><b>{val_str}</b></font>", table_cell_center)
            else:
                p = Paragraph(val_str, table_cell_style)
            formatted_row.append(p)
        table_content.append(formatted_row)

    # Automatic column width distribution if not passed
    total_w = 760  # Landscape A4 printable width (842 - 72)
    if not col_widths:
        w_per_col = total_w / len(headers)
        col_widths = [w_per_col] * len(headers)

    data_table = Table(table_content, colWidths=col_widths, repeatRows=1)
    data_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#2b1b17')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.HexColor('#ffffff')),
        ('ALIGN', (0, 0), (-1, 0), 'CENTER'),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 6),
        ('TOPPADDING', (0, 0), (-1, 0), 6),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.HexColor('#ffffff'), colors.HexColor('#faf7f2')]),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e0dbd1')),
        ('TOPPADDING', (0, 1), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 1), (-1, -1), 4),
        ('LEFTPADDING', (0, 0), (-1, -1), 5),
        ('RIGHTPADDING', (0, 0), (-1, -1), 5),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
    ]))

    story.append(data_table)

    # Build document
    doc.build(story, canvasmaker=NumberedCanvas)
    return buffer.getvalue()
